import { FC, SVGProps } from 'react'

/** fill-rule / clip-rule を evenodd にするかはパスごとに違うため、d と組にして持つ */
export type IconPath = { d: string; evenodd?: boolean }

type IconOptions = {
  viewBox?: string
  /** 既定の表示幅(px)。利用側の width で上書きできる */
  width?: number
  /** 塗りではなく線で描くアイコン(heroicons の outline) */
  isStroke?: boolean
}

/**
 * パスからアイコン部品を作る。
 * paths に文字列を渡した場合は evenodd のパス1本として扱う(heroicons の solid はほぼこの形)。
 */
export const createIcon = (
  paths: string | IconPath[],
  { viewBox = '0 0 24 24', width: defaultWidth = 20, isStroke = false }: IconOptions = {},
): FC<SVGProps<SVGSVGElement>> => {
  const list = typeof paths === 'string' ? [{ d: paths, evenodd: true }] : paths
  const Icon: FC<SVGProps<SVGSVGElement>> = ({ width = defaultWidth, ...props }) => (
    <svg
      fill={isStroke ? 'none' : 'currentColor'}
      stroke={isStroke ? 'currentColor' : undefined}
      strokeWidth={isStroke ? 2 : undefined}
      viewBox={viewBox}
      xmlns='http://www.w3.org/2000/svg'
      aria-hidden='true'
      width={width}
      {...props}
    >
      {list.map(({ d, evenodd }) => (
        <path
          key={d}
          d={d}
          fillRule={evenodd ? 'evenodd' : undefined}
          clipRule={evenodd ? 'evenodd' : undefined}
          strokeLinecap={isStroke ? 'round' : undefined}
          strokeLinejoin={isStroke ? 'round' : undefined}
        />
      ))}
    </svg>
  )
  return Icon
}

